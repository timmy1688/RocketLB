// 本文件生成要在节点上执行的 shell。控制面不直接拼命令，而是把整段脚本从 SSH 的标准输入送进去。
// 脚本只做三件事：安装软件、预检写入、失败后还原。
package publish

import (
	"encoding/base64"
	"fmt"
	"path/filepath"
	"regexp"
	"strings"
)

// nginxBin 是 Ubuntu 上 nginx 的固定路径，预检时用它执行 nginx -t，不依赖节点的 PATH。
// pathLine 补上 sbin，避免 sudo 后找不到 systemctl 和 nginx。
const (
	nginxBin = "/usr/sbin/nginx"
	pathLine = `export PATH="/usr/sbin:/usr/bin:/sbin:/bin:$PATH"`
)

// idRe 只接受 UUID，备份目录名必须匹配它。
var idRe = regexp.MustCompile(`^[a-f0-9-]{36}$`)

// scriptFile 是准备写到节点上的一个文件。Mode 只用 0644、0600 或 0755。
type scriptFile struct {
	Path    string
	Content string
	Mode    uint32
}

// installScript 在两台一起部署的节点上安装 nginx 和 keepalived，并写入网关常用的系统参数。
func installScript() string {
	return installScriptFor("both")
}

// installScriptFor 按角色安装。both 两样都装，lvs 只装转发，nginx 只装 nginx。
// Ubuntu 20.04、22.04、24.04 用同一套命令：系统源的软件包，安装前换成国内镜像。已经装好就跳过 apt。
// 连接队列、本地端口和文件句柄与 nginx 里的 worker_connections 16384、worker_rlimit_nofile 65535 对齐。
func installScriptFor(role string) string {
	var b strings.Builder
	b.WriteString(installHead)
	b.WriteString(aptHelpers)
	switch role {
	case "lvs":
		b.WriteString("pkg_ok keepalived || rm -f /etc/keepalived/keepalived.conf\n")
		b.WriteString("apt_install keepalived ipvsadm\n\n")
	case "nginx":
		b.WriteString(installNginxPackages)
		b.WriteString("apt_install nginx libnginx-mod-stream\n")
		b.WriteString(requireStream)
	default:
		b.WriteString(installNginxPackages)
		b.WriteString("pkg_ok keepalived || rm -f /etc/keepalived/keepalived.conf\n")
		b.WriteString("apt_install nginx libnginx-mod-stream keepalived ipvsadm\n")
		b.WriteString(requireStream)
	}
	b.WriteString(installSysctl)
	if role != "lvs" {
		b.WriteString(nginxUnit)
	}
	b.WriteString("echo rocketlb-install-ok\n")
	return b.String()
}

// aptHelpers 把 Ubuntu 官方源换成阿里云，并在缺包时才执行 apt-get update。
const aptHelpers = `use_cn_mirror() {
  local f
  for f in /etc/apt/sources.list /etc/apt/sources.list.d/*.sources /etc/apt/sources.list.d/*.list; do
    [ -f "$f" ] || continue
    if grep -Eq 'mirrors\.(aliyun|cloud\.tencent|huaweicloud|tuna\.tsinghua)\.|mirrors\.ustc\.edu\.cn|repo\.huaweicloud\.com' "$f"; then
      continue
    fi
    sed -i \
      -e 's|https\?://archive.ubuntu.com/ubuntu|https://mirrors.aliyun.com/ubuntu|g' \
      -e 's|https\?://security.ubuntu.com/ubuntu|https://mirrors.aliyun.com/ubuntu|g' \
      -e 's|https\?://cn.archive.ubuntu.com/ubuntu|https://mirrors.aliyun.com/ubuntu|g' \
      -e 's|https\?://mirrors.edge.kernel.org/ubuntu|https://mirrors.aliyun.com/ubuntu|g' \
      "$f"
  done
}

pkg_ok() {
  dpkg-query -W -f '${Status}' "$1" 2>/dev/null | grep -q 'install ok installed'
}

apt_install() {
  local p missing=0
  for p in "$@"; do
    if ! pkg_ok "$p"; then
      missing=1
      break
    fi
  done
  if [ "$missing" -eq 0 ]; then
    return 0
  fi
  use_cn_mirror
  apt-get update
  apt-get install -y --no-install-recommends "$@"
}

`

// installNginxPackages 安装系统自带的 nginx，并带上 stream 动态模块。20.04、22.04、24.04 的包名相同。
// 节点上如果还留着以前编译出来的 nginx，先清掉，避免和软件包抢同一个文件。
const installNginxPackages = `prepare_distro_nginx() {
  if pkg_ok nginx-common; then
    return 0
  fi
  systemctl stop nginx >/dev/null 2>&1 || true
  rm -f /usr/sbin/nginx /etc/systemd/system/nginx.service
  rm -rf /etc/nginx
  systemctl daemon-reload || true
}
prepare_distro_nginx
`

const requireStream = `if ! grep -q ngx_stream_module /etc/nginx/modules-enabled/*.conf 2>/dev/null; then
  echo "未启用 nginx stream 模块" >&2
  exit 1
fi

`

const installHead = `set -euo pipefail
export PATH="/usr/sbin:/usr/bin:/sbin:/bin:$PATH"
if [ ! -r /etc/os-release ]; then
  echo "无法识别操作系统" >&2
  exit 2
fi
. /etc/os-release
if [ "${ID:-}" != "ubuntu" ]; then
  echo "RocketLB 目前只自动安装 Ubuntu，当前是 ${ID:-unknown}" >&2
  exit 2
fi
export DEBIAN_FRONTEND=noninteractive
`

const installSysctl = `# 这些值在重启后仍生效。不写 conntrack：模块没加载时，sysctl 文件会导致开机失败。
cat > /etc/sysctl.d/99-rocketlb.conf <<'EOF'
# Generated by RocketLB. Do not edit on the node.
fs.nr_open = 1048576
net.core.somaxconn = 16384
net.core.netdev_max_backlog = 16384
net.ipv4.tcp_max_syn_backlog = 16384
net.ipv4.ip_local_port_range = 1024 65535
net.ipv4.tcp_tw_reuse = 1
net.ipv4.tcp_fin_timeout = 15
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_keepalive_time = 600
net.ipv4.tcp_keepalive_intvl = 30
net.ipv4.tcp_keepalive_probes = 3
net.ipv4.tcp_max_tw_buckets = 262144
net.ipv4.conf.all.arp_ignore = 1
net.ipv4.conf.all.arp_announce = 2
net.ipv4.conf.lo.arp_ignore = 1
net.ipv4.conf.lo.arp_announce = 2
net.ipv4.conf.all.rp_filter = 2
EOF
sysctl -p /etc/sysctl.d/99-rocketlb.conf >/dev/null

# 防火墙跟踪连接时用。模块不存在就跳过，不让安装失败。
modprobe nf_conntrack 2>/dev/null || true
if [ -e /proc/sys/net/netfilter/nf_conntrack_max ]; then
  sysctl -w net.netfilter.nf_conntrack_max=1048576 >/dev/null
  mkdir -p /etc/modules-load.d
  echo nf_conntrack > /etc/modules-load.d/rocketlb-conntrack.conf
  echo 'options nf_conntrack hashsize=262144' > /etc/modprobe.d/rocketlb-conntrack.conf
  cat > /etc/sysctl.d/99-rocketlb-conntrack.conf <<'EOF'
# Generated by RocketLB. Do not edit on the node.
net.netfilter.nf_conntrack_max = 1048576
EOF
fi

`

const nginxUnit = `mkdir -p /etc/systemd/system/nginx.service.d
cat > /etc/systemd/system/nginx.service.d/rocketlb.conf <<'EOF'
[Service]
LimitNOFILE=65535
EOF
systemctl daemon-reload
if systemctl is-active --quiet nginx; then
  systemctl restart nginx
fi
`

// prepareScript 生成预检脚本：先备份现有文件，再写入新文件，最后跑 nginx -t。任一步失败都会立刻还原，还不会 reload。
func prepareScript(backupID string, files []scriptFile) (string, error) {
	if err := validID(backupID); err != nil {
		return "", err
	}
	for _, file := range files {
		if err := validFile(file); err != nil {
			return "", err
		}
	}
	backup := backupPath(backupID)
	var b strings.Builder
	b.WriteString("set -euo pipefail\n")
	b.WriteString(pathLine + "\n")
	b.WriteString("umask 077\n")
	fmt.Fprintf(&b, "mkdir -p %q /usr/libexec/rocketlb /etc/nginx /etc/keepalived /var/lib/rocketlb/original\n", backup)
	b.WriteString(snapshot(backup))
	b.WriteString("restore_all() {\ntrap - ERR\n")
	b.WriteString(restoreBody(backup))
	b.WriteString("}\ntrap restore_all ERR\n")
	for _, file := range files {
		fmt.Fprintf(&b, "mkdir -p %q\n", filepath.Dir(file.Path))
		enc := base64.StdEncoding.EncodeToString([]byte(file.Content))
		fmt.Fprintf(&b, "printf '%%s' '%s' | base64 -d > %q\n", enc, file.Path)
		fmt.Fprintf(&b, "chmod %04o %q\n", file.Mode, file.Path)
	}
	if hasPath(files, "/etc/nginx/nginx.conf") {
		fmt.Fprintf(&b, "if [ ! -x %s ]; then echo '未安装 nginx' >&2; exit 3; fi\n", nginxBin)
		fmt.Fprintf(&b, "%s -t\n", nginxBin)
	}
	if hasPath(files, "/etc/keepalived/keepalived.conf") {
		b.WriteString("if [ ! -x /usr/sbin/keepalived ]; then echo '未安装 keepalived' >&2; exit 3; fi\n")
		b.WriteString("/usr/sbin/keepalived -t -f /etc/keepalived/keepalived.conf\n")
	}
	b.WriteString("trap - ERR\n")
	b.WriteString("echo rocketlb-prepare-ok\n")
	return b.String(), nil
}

// enableLVSReal 把 nginx 节点上回环 VIP 做成开机服务。ip addr 本身不跨重启，只执行一次脚本的话，机器重启后 DR 包没人收。
const enableLVSReal = `cat > /etc/systemd/system/rocketlb-lvs-real.service << 'EOF'
[Unit]
Description=RocketLB nginx node VIP on loopback
After=network-online.target
Wants=network-online.target
Before=nginx.service

[Service]
Type=oneshot
ExecStart=/usr/libexec/rocketlb/lvs-real
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable rocketlb-lvs-real.service
systemctl start rocketlb-lvs-real.service
`

const disableLVSReal = `systemctl disable --now rocketlb-lvs-real.service >/dev/null 2>&1 || true
rm -f /etc/systemd/system/rocketlb-lvs-real.service
systemctl daemon-reload >/dev/null 2>&1 || true
`

// activateScript 在所有节点都预检通过后才执行。这台机器这次没分到的服务会停掉，避免两台一起改成四台分开后，转发机器还在跑 nginx，或者 nginx 机器还占着 VIP。
func activateScript(files []scriptFile) string {
	var b strings.Builder
	b.WriteString("set -euo pipefail\n")
	b.WriteString(pathLine + "\n")
	if hasPath(files, "/usr/libexec/rocketlb/lvs-real") {
		b.WriteString(enableLVSReal)
	} else {
		b.WriteString(disableLVSReal)
	}
	if hasPath(files, "/etc/keepalived/keepalived.conf") {
		b.WriteString(`if [ -x /usr/libexec/rocketlb/lvs-prep ] && grep -q 'lb_kind DR' /etc/keepalived/keepalived.conf; then
  /usr/libexec/rocketlb/lvs-prep
fi
systemctl enable keepalived
if systemctl is-active --quiet keepalived; then
  systemctl reload keepalived || systemctl restart keepalived
else
  systemctl start keepalived
fi
if [ -x /usr/libexec/rocketlb/lvs-prep ] && grep -q 'lb_kind DR' /etc/keepalived/keepalived.conf; then
  /usr/libexec/rocketlb/lvs-prep sync
fi
`)
	} else {
		b.WriteString("systemctl stop keepalived || true\nsystemctl disable keepalived || true\nipvsadm -C || true\n")
	}
	if hasPath(files, "/etc/nginx/nginx.conf") {
		b.WriteString(`if [ -f /etc/nginx/nginx.conf ] && grep -q "Generated by RocketLB" /etc/nginx/nginx.conf; then
  systemctl enable nginx
  if systemctl is-active --quiet nginx; then
    systemctl reload nginx
  else
    systemctl start nginx
  fi
fi
`)
	} else {
		b.WriteString("systemctl stop nginx || true\nsystemctl disable nginx || true\n")
	}
	b.WriteString("echo rocketlb-activate-ok\n")
	return b.String()
}

// restoreScript 用这次发布的备份把节点恢复回去，并重新加载还活着的服务。备份目录不存在就什么也不做。
func restoreScript(backupID string) (string, error) {
	if err := validID(backupID); err != nil {
		return "", err
	}
	backup := backupPath(backupID)
	var b strings.Builder
	b.WriteString("set -euo pipefail\n")
	b.WriteString(pathLine + "\n")
	fmt.Fprintf(&b, "if [ ! -d %q ]; then echo rocketlb-restore-skip; exit 0; fi\n", backup)
	b.WriteString(restoreBody(backup))
	b.WriteString(`if [ -f /etc/nginx/nginx.conf ] && grep -q "Generated by RocketLB" /etc/nginx/nginx.conf; then
  if [ -x /usr/sbin/nginx ]; then /usr/sbin/nginx -t; fi
  systemctl enable nginx
  if systemctl is-active --quiet nginx; then systemctl reload nginx; else systemctl start nginx; fi
fi
if [ -f /etc/keepalived/keepalived.conf ] && grep -q "Generated by RocketLB" /etc/keepalived/keepalived.conf; then
  systemctl enable keepalived
  if systemctl is-active --quiet keepalived; then systemctl reload keepalived || systemctl restart keepalived; else systemctl start keepalived; fi
  if [ -x /usr/libexec/rocketlb/lvs-prep ] && grep -q 'lb_kind DR' /etc/keepalived/keepalived.conf; then
    /usr/libexec/rocketlb/lvs-prep sync
  fi
fi
if [ -x /usr/libexec/rocketlb/lvs-real ]; then
` + enableLVSReal + `else
` + disableLVSReal + `fi
echo rocketlb-restore-ok
`)
	return b.String(), nil
}

// snapshot 把节点上现有的 nginx、keepalived 和检查脚本复制到备份目录。文件本来不存在时放一个标记，还原时就删掉我们新建的文件。
func snapshot(backup string) string {
	return fmt.Sprintf(`if [ -f /etc/nginx/nginx.conf ] && [ ! -f /var/lib/rocketlb/original/nginx.conf ]; then
  if ! grep -q "Generated by RocketLB" /etc/nginx/nginx.conf; then
    cp -a /etc/nginx/nginx.conf /var/lib/rocketlb/original/nginx.conf
  fi
fi
if [ -f /etc/nginx/nginx.conf ]; then cp -a /etc/nginx/nginx.conf %q; else touch %q; fi
if [ -d /etc/nginx/rocketlb ]; then cp -a /etc/nginx/rocketlb %q; else touch %q; fi
if [ -f /etc/keepalived/keepalived.conf ]; then cp -a /etc/keepalived/keepalived.conf %q; else touch %q; fi
if [ -f /usr/libexec/rocketlb/check-nginx ]; then mkdir -p %q; cp -a /usr/libexec/rocketlb/check-nginx %q; else touch %q; fi
if [ -f /usr/libexec/rocketlb/check-lvs ]; then mkdir -p %q; cp -a /usr/libexec/rocketlb/check-lvs %q; else touch %q; fi
if [ -f /usr/libexec/rocketlb/lvs-prep ]; then mkdir -p %q; cp -a /usr/libexec/rocketlb/lvs-prep %q; else touch %q; fi
if [ -f /usr/libexec/rocketlb/lvs-real ]; then mkdir -p %q; cp -a /usr/libexec/rocketlb/lvs-real %q; else touch %q; fi
`,
		backup+"/nginx.conf", backup+"/no-nginx.conf",
		backup+"/rocketlb", backup+"/no-rocketlb",
		backup+"/keepalived.conf", backup+"/no-keepalived.conf",
		backup+"/libexec", backup+"/libexec/check-nginx", backup+"/no-check-nginx",
		backup+"/libexec", backup+"/libexec/check-lvs", backup+"/no-check-lvs",
		backup+"/libexec", backup+"/libexec/lvs-prep", backup+"/no-lvs-prep",
		backup+"/libexec", backup+"/libexec/lvs-real", backup+"/no-lvs-real",
	)
}

// restoreBody 按备份标记还原。有原文件就拷回，只有“原来没有”的标记就删除这次写出的文件。
func restoreBody(backup string) string {
	return fmt.Sprintf(`if [ -f %[1]q ]; then cp -a %[1]q /etc/nginx/nginx.conf; elif [ -f %[2]q ]; then rm -f /etc/nginx/nginx.conf; fi
if [ -d %[3]q ]; then rm -rf -- /etc/nginx/rocketlb; cp -a %[3]q /etc/nginx/rocketlb; elif [ -f %[4]q ]; then rm -rf -- /etc/nginx/rocketlb; fi
if [ -f %[5]q ]; then cp -a %[5]q /etc/keepalived/keepalived.conf; elif [ -f %[6]q ]; then rm -f /etc/keepalived/keepalived.conf; fi
if [ -f %[7]q ]; then mkdir -p /usr/libexec/rocketlb; cp -a %[7]q /usr/libexec/rocketlb/check-nginx; elif [ -f %[8]q ]; then rm -f /usr/libexec/rocketlb/check-nginx; fi
if [ -f %[9]q ]; then mkdir -p /usr/libexec/rocketlb; cp -a %[9]q /usr/libexec/rocketlb/check-lvs; elif [ -f %[10]q ]; then rm -f /usr/libexec/rocketlb/check-lvs; fi
if [ -f %[11]q ]; then mkdir -p /usr/libexec/rocketlb; cp -a %[11]q /usr/libexec/rocketlb/lvs-prep; elif [ -f %[12]q ]; then rm -f /usr/libexec/rocketlb/lvs-prep; fi
if [ -f %[13]q ]; then mkdir -p /usr/libexec/rocketlb; cp -a %[13]q /usr/libexec/rocketlb/lvs-real; elif [ -f %[14]q ]; then rm -f /usr/libexec/rocketlb/lvs-real; fi
`,
		backup+"/nginx.conf", backup+"/no-nginx.conf",
		backup+"/rocketlb", backup+"/no-rocketlb",
		backup+"/keepalived.conf", backup+"/no-keepalived.conf",
		backup+"/libexec/check-nginx", backup+"/no-check-nginx",
		backup+"/libexec/check-lvs", backup+"/no-check-lvs",
		backup+"/libexec/lvs-prep", backup+"/no-lvs-prep",
		backup+"/libexec/lvs-real", backup+"/no-lvs-real",
	)
}

func hasPath(files []scriptFile, path string) bool {
	for _, file := range files {
		if file.Path == path {
			return true
		}
	}
	return false
}

// backupPath 是节点上这次发布的备份目录。编号必须是 UUID，避免被拼进路径。
func backupPath(id string) string {
	return "/var/lib/rocketlb/backup/" + id
}

// validID 确认备份编号是 36 位 UUID，防止异常编号跑进 shell。
func validID(id string) error {
	if !idRe.MatchString(id) {
		return fmt.Errorf("无效的备份编号")
	}
	return nil
}

// validFile 只允许写 nginx、keepalived 和 /usr/libexec/rocketlb 下的固定路径，拒绝 .. 和其他目录。
func validFile(file scriptFile) error {
	clean := filepath.Clean(file.Path)
	if clean != file.Path || !filepath.IsAbs(clean) || strings.Contains(file.Path, "..") {
		return fmt.Errorf("拒绝写入 %s", file.Path)
	}
	switch clean {
	case "/etc/nginx/nginx.conf", "/etc/keepalived/keepalived.conf":
	default:
		if !strings.HasPrefix(clean, "/etc/nginx/rocketlb/") && !strings.HasPrefix(clean, "/usr/libexec/rocketlb/") {
			return fmt.Errorf("拒绝写入 %s", file.Path)
		}
	}
	switch file.Mode {
	case 0o644, 0o600, 0o755:
	default:
		return fmt.Errorf("拒绝文件权限 %o", file.Mode)
	}
	return nil
}
