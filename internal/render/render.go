// Package render 把数据库里的期望状态变成 nginx 和 keepalived 文件。它不连数据库，也不 SSH，只做字符串。
// 跑 nginx 的节点配置相同。keepalived 只写在转发节点上，因为单播源地址和优先级不同。
package render

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"

	"rocketlb/internal/validate"
)

// header 写在每份生成文件的开头。安装脚本靠这句话判断 nginx.conf 是不是我们生成的，避免覆盖用户原来的配置备份。
const header = "# Generated by RocketLB. Do not edit on the node.\n"

// 成员角色。空字符串按 both 处理，这样旧数据不用改。
const (
	RoleBoth  = "both"
	RoleLVS   = "lvs"
	RoleNginx = "nginx"
)

// Cluster 是渲染需要的集群字段，已经从数据库模型里摘出来，不带加密列。
type Cluster struct {
	Name      string
	VIP       string
	Prefix    int
	VRID      int
	Interface string
	AuthPass  string
	AdvertInt int
}

// Member 是一台成员。Address 会写成这台机器的 VRRP 单播源地址。
// Role 为 both 时这台机器同时转发和跑 nginx，为 lvs 时只转发，为 nginx 时只跑 nginx。
type Member struct {
	NodeID    string
	NodeName  string
	Address   string
	Priority  int
	Interface string
	Role      string
}

// Server 是上游里的一台后端，对应 nginx 的 server 行。
type Server struct {
	Address     string
	Port        int
	Weight      int
	MaxFails    int
	FailTimeout int
	Backup      bool
	Down        bool
}

// Upstream 是一组后端。Layer 为 http 或 stream，决定它进七层还是四层配置。
type Upstream struct {
	Name    string
	Layer   string
	Method  string
	Servers []Server
}

// Site 是一条七层站点。TLS 为真时要能在 Certificates 里找到同名证书。
type Site struct {
	Name       string
	ListenPort int
	ServerName string
	TLS        bool
	CertName   string
	Upstream   string
	WebSocket  bool
}

// Stream 是一条四层代理，协议是 tcp 或 udp。
type Stream struct {
	Name       string
	Protocol   string
	ListenPort int
	Upstream   string
}

// Certificate 是要写到节点上的证书和私钥。私钥只在渲染和发布时解密，预览会再藏起来。
type Certificate struct {
	Name        string
	Certificate string
	PrivateKey  string
}

// Input 是一次渲染的全部期望状态。发布前由 publish 从数据库组装。
type Input struct {
	Cluster      Cluster
	Members      []Member
	Upstreams    []Upstream
	Sites        []Site
	Streams      []Stream
	Certificates []Certificate
}

// File 是渲染结果里的一个文件。NodeID 为空表示每台节点都写同一份，例如 nginx.conf。
type File struct {
	Path    string `json:"path"`
	NodeID  string `json:"nodeId,omitempty"`
	Content string `json:"content"`
	Mode    uint32 `json:"mode"`
}

// Bundle 是一次渲染的全部文件。Hash 用来认出两次发布的内容是否相同。
type Bundle struct {
	Files []File `json:"files"`
	Hash  string `json:"hash"`
}

// Redacted 给预览用，把私钥内容换成一句说明。真正发布仍使用未打码的 Bundle。
func (b Bundle) Redacted() Bundle {
	out := b
	out.Files = append([]File(nil), b.Files...)
	for i, file := range out.Files {
		if strings.HasSuffix(file.Path, ".key") || strings.Contains(file.Content, "PRIVATE KEY") {
			out.Files[i].Content = "# 私钥已从预览中省略\n"
		}
	}
	return out
}

// Build 把期望状态变成文件。跑 nginx 的节点拿到同一份 nginx 配置，转发节点每人一份 keepalived.conf。
func Build(in Input) (Bundle, error) {
	if err := validateCluster(in.Cluster); err != nil {
		return Bundle{}, err
	}
	if err := validateMembers(in); err != nil {
		return Bundle{}, err
	}
	directors, reals, split, err := layoutOf(in.Members)
	if err != nil {
		return Bundle{}, err
	}
	weight, err := TrackWeight(priorities(directors))
	if err != nil {
		return Bundle{}, err
	}
	httpUps, streamUps, err := splitUpstreams(in.Upstreams)
	if err != nil {
		return Bundle{}, err
	}
	if err := validateListeners(in); err != nil {
		return Bundle{}, err
	}

	nginxFiles, err := nginxFiles(in, httpUps, streamUps)
	if err != nil {
		return Bundle{}, err
	}
	var files []File
	if split {
		for _, member := range reals {
			files = append(files, withNode(nginxFiles, member.NodeID)...)
			files = append(files, File{
				Path: "/usr/libexec/rocketlb/lvs-real", NodeID: member.NodeID,
				Content: realPrep(in.Cluster.VIP), Mode: 0o755,
			})
		}
		prep := lvsPrep(in.Cluster.VIP, in.Cluster.Prefix, reals, in.Sites, in.Streams, false)
		for _, member := range directors {
			files = append(files, File{
				Path: "/usr/libexec/rocketlb/lvs-prep", NodeID: member.NodeID,
				Content: prep, Mode: 0o755,
			})
		}
	} else {
		files = append(files, nginxFiles...)
		files = append(files, File{
			Path:    "/usr/libexec/rocketlb/lvs-prep",
			Content: lvsPrep(in.Cluster.VIP, in.Cluster.Prefix, reals, in.Sites, in.Streams, true),
			Mode:    0o755,
		})
	}
	for _, member := range directors {
		iface := member.Interface
		if iface == "" {
			iface = in.Cluster.Interface
		}
		files = append(files, File{
			Path:    "/usr/libexec/rocketlb/check-lvs",
			NodeID:  member.NodeID,
			Content: checkLvs(in.Cluster.VIP, in.Cluster.Prefix),
			Mode:    0o755,
		}, File{
			Path:    "/etc/keepalived/keepalived.conf",
			NodeID:  member.NodeID,
			Content: keepalivedConf(in.Cluster, member, directors, reals, in.Sites, in.Streams, iface, weight),
			Mode:    0o644,
		})
	}
	return Bundle{Files: files, Hash: hashFiles(files)}, nil
}

// nginxFiles 是跑 nginx 的节点都要有的文件。分开部署时再按节点复制一份。
func nginxFiles(in Input, httpUps, streamUps []Upstream) ([]File, error) {
	files := []File{
		{Path: "/etc/nginx/nginx.conf", Content: nginxConf(), Mode: 0o644},
		{Path: "/etc/nginx/rocketlb/http-upstreams.conf", Content: upstreamFile("http", httpUps), Mode: 0o644},
		{Path: "/etc/nginx/rocketlb/sites.conf", Content: sitesFile(in.Sites), Mode: 0o644},
		{Path: "/etc/nginx/rocketlb/stream-upstreams.conf", Content: upstreamFile("stream", streamUps), Mode: 0o644},
		{Path: "/etc/nginx/rocketlb/streams.conf", Content: streamsFile(in.Streams), Mode: 0o644},
	}
	if sitesUseTLS(in.Sites) {
		files = append(files,
			File{Path: "/etc/nginx/rocketlb/default.crt", Content: ensureNL(defaultCertPEM), Mode: 0o644},
			File{Path: "/etc/nginx/rocketlb/default.key", Content: ensureNL(defaultKeyPEM), Mode: 0o600},
		)
	}
	for _, cert := range in.Certificates {
		if err := validate.Name(cert.Name); err != nil {
			return nil, err
		}
		files = append(files,
			File{Path: "/etc/nginx/rocketlb/certs/" + cert.Name + ".crt", Content: ensureNL(cert.Certificate), Mode: 0o644},
			File{Path: "/etc/nginx/rocketlb/certs/" + cert.Name + ".key", Content: ensureNL(cert.PrivateKey), Mode: 0o600},
		)
	}
	return files, nil
}

// withNode 把同一份文件标给某一台节点。NodeID 为空的文件会写到每一台，分开部署时不能这么做。
func withNode(files []File, nodeID string) []File {
	out := make([]File, len(files))
	for i, file := range files {
		file.NodeID = nodeID
		out[i] = file
	}
	return out
}

// layoutOf 区分两种部署。全部是 both（或没填）就是两台一起；否则必须是至少两台转发加两台 nginx。
func layoutOf(members []Member) (directors, reals []Member, split bool, err error) {
	if len(members) < 2 {
		return nil, nil, false, fmt.Errorf("发布至少需要两个节点")
	}
	var bothN, lvsN, nginxN int
	for _, member := range members {
		switch normalizeRole(member.Role) {
		case RoleBoth:
			bothN++
		case RoleLVS:
			lvsN++
		case RoleNginx:
			nginxN++
		default:
			return nil, nil, false, fmt.Errorf("成员角色无效")
		}
	}
	if bothN > 0 && (lvsN > 0 || nginxN > 0) {
		return nil, nil, false, fmt.Errorf("一个集群里不能混用两种部署")
	}
	if bothN > 0 {
		return members, members, false, nil
	}
	if lvsN < 2 || nginxN < 2 {
		return nil, nil, false, fmt.Errorf("分开部署需要至少两台转发和两台 nginx")
	}
	for _, member := range members {
		if normalizeRole(member.Role) == RoleLVS {
			directors = append(directors, member)
			continue
		}
		reals = append(reals, member)
	}
	return directors, reals, true, nil
}

func normalizeRole(role string) string {
	if role == "" {
		return RoleBoth
	}
	return role
}

// TrackWeight 计算 nginx 挂掉时要减掉的优先级，结果是负的最高优先级。这样故障节点会低于所有同伴。
func TrackWeight(priorities []int) (int, error) {
	if len(priorities) < 2 {
		return 0, fmt.Errorf("发布至少需要两个节点")
	}
	sorted := append([]int(nil), priorities...)
	sort.Sort(sort.Reverse(sort.IntSlice(sorted)))
	// 故障节点要被降到所有同伴之下。Keepalived 2.0.19 不会进入 FAULT，权重最低只落到 1，
	// 所以不能写 nopreempt，否则同伴永远抢不走 VIP。权重最低只能到 -253，优先级因此不能超过 253。
	if sorted[0] > 253 {
		return 0, fmt.Errorf("优先级不能超过 253，否则 nginx 停止后无法让出 VIP")
	}
	return -sorted[0], nil
}

// priorities 抽出成员优先级，交给 TrackWeight。
func priorities(members []Member) []int {
	out := make([]int, len(members))
	for i, member := range members {
		out[i] = member.Priority
	}
	return out
}

// validateCluster 在生成文件前再检查一遍集群字段，避免非法 VIP 写进配置。
func validateCluster(c Cluster) error {
	if err := validate.Name(c.Name); err != nil {
		return err
	}
	if err := validate.IPv4(c.VIP); err != nil {
		return err
	}
	if err := validate.Prefix(c.Prefix); err != nil {
		return err
	}
	if err := validate.VRID(c.VRID); err != nil {
		return err
	}
	if err := validate.Interface(c.Interface); err != nil {
		return err
	}
	if err := validate.AuthPass(c.AuthPass); err != nil {
		return err
	}
	if c.AdvertInt < 1 || c.AdvertInt > 10 {
		return fmt.Errorf("通告间隔需在 1 到 10 秒之间")
	}
	return nil
}

// validateMembers 要求成员地址是 IPv4，优先级互不相同。
func validateMembers(in Input) error {
	seen := map[string]struct{}{}
	prio := map[int]struct{}{}
	for _, member := range in.Members {
		if err := validate.IPv4(member.Address); err != nil {
			return fmt.Errorf("节点 %s: %w", member.NodeName, err)
		}
		if err := validate.Priority(member.Priority); err != nil {
			return err
		}
		if member.Interface != "" {
			if err := validate.Interface(member.Interface); err != nil {
				return err
			}
		}
		if _, ok := seen[member.NodeID]; ok {
			return fmt.Errorf("节点 %s 重复加入集群", member.NodeName)
		}
		seen[member.NodeID] = struct{}{}
		if normalizeRole(member.Role) == RoleNginx {
			continue
		}
		if _, ok := prio[member.Priority]; ok {
			return fmt.Errorf("优先级 %d 重复", member.Priority)
		}
		prio[member.Priority] = struct{}{}
	}
	return nil
}

// splitUpstreams 按七层和四层拆开上游，并给没填的权重、失败次数补上默认值。
func splitUpstreams(ups []Upstream) (httpUps, streamUps []Upstream, err error) {
	names := map[string]struct{}{}
	for _, up := range ups {
		if err := validate.Name(up.Name); err != nil {
			return nil, nil, err
		}
		if _, ok := names[up.Name]; ok {
			return nil, nil, fmt.Errorf("上游 %s 重名", up.Name)
		}
		names[up.Name] = struct{}{}
		if len(up.Servers) == 0 {
			return nil, nil, fmt.Errorf("上游 %s 没有后端", up.Name)
		}
		for i, server := range up.Servers {
			if err := validate.Host(server.Address); err != nil {
				return nil, nil, err
			}
			if err := validate.Port(server.Port); err != nil {
				return nil, nil, err
			}
			if server.Weight <= 0 {
				up.Servers[i].Weight = 1
			}
			if server.MaxFails < 0 || server.FailTimeout < 0 {
				return nil, nil, fmt.Errorf("上游 %s 的健康检查参数不合法", up.Name)
			}
			if server.MaxFails == 0 {
				up.Servers[i].MaxFails = 1
			}
			if server.FailTimeout == 0 {
				up.Servers[i].FailTimeout = 10
			}
		}
		switch up.Layer {
		case "http":
			if up.Method == "ip_hash" || up.Method == "least_conn" || up.Method == "hash" || up.Method == "round_robin" || up.Method == "" {
				httpUps = append(httpUps, up)
				continue
			}
		case "stream":
			if up.Method == "ip_hash" {
				return nil, nil, fmt.Errorf("四层上游 %s 不能使用 ip_hash", up.Name)
			}
			if up.Method == "least_conn" || up.Method == "hash" || up.Method == "round_robin" || up.Method == "" {
				streamUps = append(streamUps, up)
				continue
			}
		}
		return nil, nil, fmt.Errorf("上游 %s 的层级或算法不支持", up.Name)
	}
	return httpUps, streamUps, nil
}

// validateListeners 确认站点引用的是七层上游、四层代理引用的是四层上游，并且监听端口不冲突。
func validateListeners(in Input) error {
	httpNames := map[string]struct{}{}
	streamNames := map[string]struct{}{}
	for _, up := range in.Upstreams {
		if up.Layer == "http" {
			httpNames[up.Name] = struct{}{}
		} else {
			streamNames[up.Name] = struct{}{}
		}
	}
	certs := map[string]struct{}{}
	for _, cert := range in.Certificates {
		certs[cert.Name] = struct{}{}
	}
	used := map[string]struct{}{}
	for _, site := range in.Sites {
		if err := validate.Name(site.Name); err != nil {
			return err
		}
		if err := validate.Port(site.ListenPort); err != nil {
			return err
		}
		if err := validate.ServerName(site.ServerName); err != nil {
			return err
		}
		if _, ok := httpNames[site.Upstream]; !ok {
			return fmt.Errorf("站点 %s 引用的上游不存在或不是七层上游", site.Name)
		}
		if site.TLS {
			if _, ok := certs[site.CertName]; !ok {
				return fmt.Errorf("站点 %s 缺少证书", site.Name)
			}
		}
		key := fmt.Sprintf("%d/tcp", site.ListenPort)
		if _, ok := used[key]; ok {
			return fmt.Errorf("监听 %s 冲突", key)
		}
		used[key] = struct{}{}
	}
	for _, stream := range in.Streams {
		if err := validate.Name(stream.Name); err != nil {
			return err
		}
		if stream.Protocol != "tcp" && stream.Protocol != "udp" {
			return fmt.Errorf("四层代理 %s 的协议只能是 tcp 或 udp", stream.Name)
		}
		if err := validate.Port(stream.ListenPort); err != nil {
			return err
		}
		if _, ok := streamNames[stream.Upstream]; !ok {
			return fmt.Errorf("四层代理 %s 引用的上游不存在或不是四层上游", stream.Name)
		}
		key := fmt.Sprintf("%d/%s", stream.ListenPort, stream.Protocol)
		if _, ok := used[key]; ok {
			return fmt.Errorf("监听 %s 冲突", key)
		}
		used[key] = struct{}{}
	}
	return nil
}

// hashFiles 按路径和内容算一个 SHA256。节点顺序不影响结果。
func hashFiles(files []File) string {
	cp := append([]File(nil), files...)
	sort.Slice(cp, func(i, j int) bool {
		if cp[i].NodeID == cp[j].NodeID {
			return cp[i].Path < cp[j].Path
		}
		return cp[i].NodeID < cp[j].NodeID
	})
	h := sha256.New()
	for _, file := range cp {
		fmt.Fprintf(h, "%s\n%s\n%s\n", file.NodeID, file.Path, file.Content)
	}
	return hex.EncodeToString(h.Sum(nil))
}

// ensureNL 让证书文件以换行结尾，避免 nginx 读到被截断的 PEM。
func ensureNL(s string) string {
	if s == "" || strings.HasSuffix(s, "\n") {
		return s
	}
	return s + "\n"
}
