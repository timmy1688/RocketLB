// 本文件为每一台成员生成 keepalived.conf。优先级高的节点在两边都健康时持有 VIP。
package render

import (
	"fmt"
	"sort"
	"strings"
)

// keepalivedConf 为某一台转发节点生成配置。所有节点都写 state BACKUP，优先级高的会抢到 VIP。不写 nopreempt，否则 2.0.19 上故障后同伴抢不走地址。
// reals 是真正跑 nginx 的机器。两台一起部署时，转发节点和 nginx 是同一批机器。
func keepalivedConf(cluster Cluster, self Member, peers []Member, reals []Member, sites []Site, streams []Stream, iface string, weight int) string {
	var lines []string
	for _, member := range peers {
		if member.NodeID == self.NodeID {
			continue
		}
		lines = append(lines, "        "+member.Address)
	}
	return header + fmt.Sprintf(`global_defs {
    router_id %s
    script_user root
    enable_script_security
}

vrrp_script chk_lvs {
    script "/usr/libexec/rocketlb/check-lvs"
    interval 2
    timeout 2
    weight %d
    fall 2
    rise 2
}

vrrp_instance VI_%d {
    state BACKUP
    interface %s
    virtual_router_id %d
    priority %d
    advert_int %d
    unicast_src_ip %s
    unicast_peer {
%s
    }
    authentication {
        auth_type PASS
        auth_pass %s
    }
    virtual_ipaddress {
        %s/%d
    }
    track_script {
        chk_lvs
    }
    notify "/usr/libexec/rocketlb/lvs-prep"
}
%s`, cluster.Name, weight, cluster.VRID, iface, cluster.VRID, self.Priority, cluster.AdvertInt, self.Address, strings.Join(lines, "\n"), cluster.AuthPass, cluster.VIP, cluster.Prefix, virtualServers(cluster.VIP, reals, sites, streams))
}

// listenKey 是一个对外端口。七层固定是 TCP，四层可能是 UDP。
type listenKey struct {
	proto string
	port  int
}

// listenKeys 收集对外端口。同一个端口只保留一条，方便配置稳定、哈希不变。
func listenKeys(sites []Site, streams []Stream) []listenKey {
	seen := map[listenKey]struct{}{}
	var keys []listenKey
	add := func(proto string, port int) {
		key := listenKey{proto, port}
		if _, ok := seen[key]; ok {
			return
		}
		seen[key] = struct{}{}
		keys = append(keys, key)
	}
	for _, site := range sites {
		add("TCP", site.ListenPort)
	}
	for _, stream := range streams {
		proto := "TCP"
		if stream.Protocol == "udp" {
			proto = "UDP"
		}
		add(proto, stream.ListenPort)
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].port == keys[j].port {
			return keys[i].proto < keys[j].proto
		}
		return keys[i].port < keys[j].port
	})
	return keys
}

func sortedMembers(members []Member) []Member {
	reals := append([]Member(nil), members...)
	sort.Slice(reals, func(i, j int) bool { return reals[i].Address < reals[j].Address })
	return reals
}

// virtualServers 为每个监听端口写一段 LVS。算法是轮询，转发用 DR，响应从各台 nginx 自己的网卡直接回去。
func virtualServers(vip string, members []Member, sites []Site, streams []Stream) string {
	keys := listenKeys(sites, streams)
	reals := sortedMembers(members)
	var b strings.Builder
	for _, key := range keys {
		check := "TCP_CHECK"
		if key.proto == "UDP" {
			check = "UDP_CHECK"
		}
		fmt.Fprintf(&b, "\nvirtual_server %s %d {\n    delay_loop 3\n    lb_algo rr\n    lb_kind DR\n    protocol %s\n", vip, key.port, key.proto)
		for _, member := range reals {
			fmt.Fprintf(&b, "    real_server %s %d {\n        weight 1\n        %s {\n            connect_timeout 3\n            connect_port %d\n        }\n    }\n", member.Address, key.port, check, key.port)
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// ipvsCommands 用 ipvsadm 把规则补上。keepalived 成为 MASTER 时会调用；规则已经存在就忽略错误。
func ipvsCommands(vip string, members []Member, sites []Site, streams []Stream) string {
	var b strings.Builder
	for _, key := range listenKeys(sites, streams) {
		flag := "-t"
		if key.proto == "UDP" {
			flag = "-u"
		}
		fmt.Fprintf(&b, "ipvsadm -A %s %s:%d -s rr 2>/dev/null || true\n", flag, vip, key.port)
		for _, member := range sortedMembers(members) {
			fmt.Fprintf(&b, "ipvsadm -a %s %s:%d -r %s:%d -g -w 1 2>/dev/null || true\n", flag, vip, key.port, member.Address, key.port)
		}
	}
	return b.String()
}

// lvsPrep 在转发节点上执行：加载 IPVS。holdLocal 为真时在 lo 上放一份 VIP，因为这台机器自己也跑 nginx。分开部署时删掉 lo 上的 VIP，避免转发机器把包留给自己。
// 只有网卡上真正挂着 VIP 的那台保留转发规则。备机如果也挂着规则，转过来的包会被它再转一次。
func lvsPrep(vip string, prefix int, members []Member, sites []Site, streams []Stream, holdLocal bool) string {
	local := fmt.Sprintf("ip addr del %s/32 dev lo 2>/dev/null || true\n", vip)
	if holdLocal {
		local = fmt.Sprintf("ip addr replace %s/32 dev lo\n", vip)
	}
	return fmt.Sprintf(`#!/bin/sh
# Generated by RocketLB. Do not edit on the node.
set -eu
printf 'ip_vs\nip_vs_rr\n' > /etc/modules-load.d/rocketlb-ipvs.conf
modprobe ip_vs 2>/dev/null || true
modprobe ip_vs_rr 2>/dev/null || true
cat > /etc/sysctl.d/99-rocketlb-lvs.conf <<'EOF'
net.ipv4.conf.all.arp_ignore = 1
net.ipv4.conf.all.arp_announce = 2
net.ipv4.conf.lo.arp_ignore = 1
net.ipv4.conf.lo.arp_announce = 2
net.ipv4.conf.all.rp_filter = 2
EOF
sysctl -p /etc/sysctl.d/99-rocketlb-lvs.conf >/dev/null
%sapply_vs() {
%s}
clear_vs() {
  command -v ipvsadm >/dev/null 2>&1 || return 0
  ipvsadm -C 2>/dev/null || true
}
state=${3:-}
if [ "${1:-}" = "sync" ]; then
  if ip -4 -o addr show | grep -q ' %s/%d '; then
    state=MASTER
  else
    state=BACKUP
  fi
fi
case "$state" in
  MASTER) apply_vs ;;
  BACKUP|FAULT|STOP) clear_vs ;;
esac
`, local, ipvsCommands(vip, members, sites, streams), vip, prefix)
}

// realPrep 只在「只跑 nginx」的机器上执行。lo 上的 VIP 用来接收转发过来的包，这台机器自己不做转发。
func realPrep(vip string) string {
	return fmt.Sprintf(`#!/bin/sh
# Generated by RocketLB. Do not edit on the node.
set -eu
cat > /etc/sysctl.d/99-rocketlb-lvs.conf <<'EOF'
net.ipv4.conf.all.arp_ignore = 1
net.ipv4.conf.all.arp_announce = 2
net.ipv4.conf.lo.arp_ignore = 1
net.ipv4.conf.lo.arp_announce = 2
net.ipv4.conf.all.rp_filter = 2
EOF
sysctl -p /etc/sysctl.d/99-rocketlb-lvs.conf >/dev/null
ip addr replace %s/32 dev lo
`, vip)
}
